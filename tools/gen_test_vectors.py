#!/usr/bin/env python3
"""Generate test/can_vectors.h from docs/can_matrix.dbc with cantools.

The C unit tests unpack these frames with the hand-written code in
common/src/can_matrix.c and compare against the values cantools encoded,
so any drift between the DBC and the C code fails the build.

Usage: python3 tools/gen_test_vectors.py docs/can_matrix.dbc test/can_vectors.h
"""
import random
import sys

import cantools


def crc8_j1850(data):
    crc = 0xFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1D) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc ^ 0xFF


def e2e_crc(can_id, payload, crc_pos):
    covered = [can_id & 0xFF, can_id >> 8] + [b for i, b in enumerate(payload) if i != crc_pos]
    return crc8_j1850(covered)


def main(dbc_path, out_path):
    db = cantools.database.load_file(dbc_path)
    rnd = random.Random(1234)  # deterministic vectors
    lines = [
        "/* AUTO-GENERATED by tools/gen_test_vectors.py from docs/can_matrix.dbc - do not edit */",
        "#ifndef CAN_VECTORS_H", "#define CAN_VECTORS_H", "#include <stdint.h>", "",
    ]

    eng = db.get_message_by_name("EngineData")
    lines.append("typedef struct { uint16_t rpm_raw, speed_raw; uint8_t coolant_raw, alive, crc; uint8_t frame[8]; } engine_vec_t;")
    lines.append("static const engine_vec_t ENGINE_VECTORS[] = {")
    for _ in range(16):
        raw = dict(EngineSpeed=rnd.randint(0, 0xFFFF), VehicleSpeed=rnd.randint(0, 0xFFFF),
                   CoolantTemp=rnd.randint(0, 255), EngineData_Alive=rnd.randint(0, 15), EngineData_CRC=0)
        frame = bytearray(eng.encode(raw, scaling=False, strict=False))
        frame[6] = 0xFF  # reserved byte as sent by the C packer
        raw["EngineData_CRC"] = e2e_crc(eng.frame_id, frame, 7)
        frame[7] = raw["EngineData_CRC"]
        lines.append("    { %uU, %uU, %uU, %uU, %uU, { %s } }," % (
            raw["EngineSpeed"], raw["VehicleSpeed"], raw["CoolantTemp"], raw["EngineData_Alive"],
            raw["EngineData_CRC"], ", ".join("0x%02XU" % b for b in frame)))
    lines.append("};")

    body = db.get_message_by_name("BodyStatus")
    lines.append("typedef struct { uint8_t bits, alive, crc; uint8_t frame[4]; } body_vec_t;")
    lines.append("static const body_vec_t BODY_VECTORS[] = {")
    for _ in range(16):
        bits = rnd.randint(0, 31)
        raw = dict(TurnLeft=bits & 1, TurnRight=(bits >> 1) & 1, HighBeam=(bits >> 2) & 1,
                   DoorOpen=(bits >> 3) & 1, SeatbeltUnfastened=(bits >> 4) & 1,
                   BodyStatus_Alive=rnd.randint(0, 15), BodyStatus_CRC=0)
        frame = bytearray(body.encode(raw, scaling=False, strict=False))
        crc = e2e_crc(body.frame_id, frame, 3)
        frame[3] = crc
        lines.append("    { %uU, %uU, %uU, { %s } }," % (bits, raw["BodyStatus_Alive"], crc,
                                                        ", ".join("0x%02XU" % b for b in frame)))
    lines.append("};")

    cl = db.get_message_by_name("ClusterStatus")
    lines.append("typedef struct { uint8_t fuel; uint32_t odo; uint8_t warn, dtc, alive, crc; uint8_t frame[8]; } cluster_vec_t;")
    lines.append("static const cluster_vec_t CLUSTER_VECTORS[] = {")
    for _ in range(16):
        raw = dict(FuelLevel=rnd.randint(0, 100), Odometer=rnd.randint(0, 0xFFFFFF),
                   WarningBits=rnd.randint(0, 255), DtcCount=rnd.randint(0, 6),
                   ClusterStatus_Alive=rnd.randint(0, 15), ClusterStatus_CRC=0)
        frame = bytearray(cl.encode(raw, scaling=False, strict=False))
        crc = e2e_crc(cl.frame_id, frame, 7)
        frame[7] = crc
        lines.append("    { %uU, %uUL, %uU, %uU, %uU, %uU, { %s } }," % (
            raw["FuelLevel"], raw["Odometer"], raw["WarningBits"], raw["DtcCount"],
            raw["ClusterStatus_Alive"], crc, ", ".join("0x%02XU" % b for b in frame)))
    lines.append("};")

    lines += ["", "#endif", ""]
    with open(out_path, "w", encoding="ascii") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
